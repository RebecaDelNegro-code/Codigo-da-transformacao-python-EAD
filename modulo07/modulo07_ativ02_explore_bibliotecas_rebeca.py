import utilidades

num1 = 10
num2 = 5

print('"""Teste De Utilidades"""')
print(f'Números Utilizados: {num1} e {num2}')
print(f' Usando Adição({num1} + {num2}):', utilidades.soma(num1, num2))
print(f' Usando subtracão({num1} - {num2}):', utilidades.subtrair(num1, num2))
print(f' Usando Multiplicação({num1} * {num2}):', utilidades.multiplicar(num1, num2))
print(f' Usando Divisão({num1} / {num2}):', utilidades.dividir(num1, num2))
print(f' Usando Divisão Inteira({num1} // {num2}):', utilidades.divisao_inteira(num1, num2))
print(f' Usando Resto De Divisão({num1} % {num2}):', utilidades.resto_divisao(num1, num2))
print(f' Usando Potencia({num1} ** {num2}):', utilidades.potencia(num1, num2))
print(f' Usando Calcular Média({num1}  {num2}):', utilidades.calcular_media(num1, num2))
print(f' Usando par({num1} $ {num2}):', utilidades.e_par(num1, num2))